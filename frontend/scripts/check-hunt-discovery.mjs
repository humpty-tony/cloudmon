import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createServer} from 'vite';
import {chromium} from 'playwright';

const root=fileURLToPath(new URL('..',import.meta.url));
const output=new URL('../test-results/hunt-discovery/',import.meta.url);
await mkdir(output,{recursive:true});
const server=await createServer({root,cacheDir:'node_modules/.vite-hunt-discovery',server:{host:'127.0.0.1',port:5282,strictPort:true}});
await server.listen();
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:800}});
page.setDefaultTimeout(5000);
const errors=[];page.on('pageerror',error=>errors.push(String(error)));
try {
  await page.goto('http://127.0.0.1:5282');
  assert.equal(await page.evaluate(()=>!!window.go),false,'Browser preview only; never native capture');
  await page.getByRole('button',{name:/Import a dump/}).click();
  await page.locator('input[type=file]').setInputFiles({name:'synthetic-hunt-discovery.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({Records:[{eventVersion:'1.11',eventID:'synthetic-hunt-discovery',eventTime:'2026-09-26T12:00:00Z',eventName:'GetObject',eventSource:'s3.amazonaws.com',awsRegion:'us-east-1',sourceIPAddress:'192.0.2.1',userIdentity:{type:'Root',arn:'arn:aws:iam::111122223333:root',accountId:'111122223333'}}]}))});
  await page.getByRole('button',{name:'Load dump',exact:true}).click();
  await page.locator('.workbench-results .row').first().waitFor();
  await page.evaluate(async()=>{
    const {backend}=await import('/src/api/backend.ts');
    window.huntDiscoveryRuns={hunt:0,rules:0};
    for(const [method,key] of [['hunt','hunt'],['sigmaRun','rules']]){
      const original=backend[method].bind(backend);
      backend[method]=(...args)=>{window.huntDiscoveryRuns[key]++;return original(...args)};
    }
  });
  await page.getByRole('button',{name:'Hunt',exact:true}).click();
  const hunt=page.getByRole('main',{name:'Hunt workspace'});
  const text=hunt.getByRole('textbox',{name:'Typed indicators',exact:true});
  await hunt.getByRole('button',{name:'Add example indicator',exact:true}).click();
  assert.equal(await text.inputValue(),'ip 192.0.2.1');
  await text.fill('event my-existing-draft');
  await hunt.getByRole('button',{name:'Add example indicator',exact:true}).click();
  assert.equal(await text.inputValue(),'event my-existing-draft\nip 192.0.2.1','Examples append, never replace drafts');
  await hunt.getByLabel('Indicator type',{exact:true}).selectOption('arn');
  await hunt.getByLabel('Indicator value',{exact:true}).fill('arn:aws:s3:::example-bucket');
  await hunt.getByRole('button',{name:'Add indicator',exact:true}).click();
  assert.match(await text.inputValue(),/\narn arn:aws:s3:::example-bucket$/);
  assert.ok(await hunt.locator('.hunt-format-examples').isVisible(),'Formats remain visible after typing');
  assert.equal(await hunt.getByRole('tabpanel',{name:'Indicators',exact:true}).getByLabel('Hunt scope').locator('option[value=workbench]').textContent(),'Current event filters');
  await page.screenshot({path:fileURLToPath(new URL('indicators-1280.png',output))});
  await hunt.getByRole('tab',{name:'Event sequences',exact:true}).click();
  const starter=hunt.getByRole('button',{name:'Load sequence example',exact:true});
  await starter.click();
  assert.match(await hunt.getByLabel('Step A search',{exact:true}).inputValue(),/ConsoleLogin/);
  assert.match(await hunt.getByLabel('Step B search',{exact:true}).inputValue(),/GetObject/);
  assert.equal(await starter.isDisabled(),true,'Nonempty sequence cannot be replaced silently');
  await page.screenshot({path:fileURLToPath(new URL('sequences-1280.png',output))});
  await hunt.getByRole('tab',{name:'Rules',exact:true}).click();
  assert.equal(await hunt.locator('.cm-content').isVisible(),false,'YAML is progressive disclosure');
  await hunt.getByRole('button',{name:/^Choose a rule/}).click();
  const choice=page.locator('.pop-menu .menu-item-main').filter({hasText:'Root account activity'}).first();
  await choice.click();
  assert.match(await hunt.locator('.sg-fname').textContent(),/AWS Root Account Activity/);
  await page.screenshot({path:fileURLToPath(new URL('rules-1280.png',output))});
  await hunt.getByRole('button',{name:'Edit YAML',exact:true}).click();
  const editor=hunt.locator('.cm-content');
  await editor.fill('title: Expert draft\nlogsource:\n  product: aws\n  service: cloudtrail\ndetection:\n  selection:\n    userIdentity.type: Root\n  condition: selection');
  await hunt.getByRole('button',{name:'Hide YAML',exact:true}).click();
  await hunt.getByRole('button',{name:'Edit YAML',exact:true}).click();
  assert.match(await editor.innerText(),/Expert draft/,'Expert edits survive disclosure');
  await page.screenshot({path:fileURLToPath(new URL('rules-editor-1280.png',output))});
  assert.deepEqual(await page.evaluate(()=>window.huntDiscoveryRuns),{hunt:0,rules:0},'No examples, choices, or edits automatically run');
  await hunt.getByRole('button',{name:'▶ Run',exact:true}).click();
  await hunt.getByText('Sigma testing needs the desktop app (the Go engine).',{exact:false}).waitFor();
  assert.equal(await page.evaluate(()=>window.huntDiscoveryRuns.rules),1);
  await hunt.getByRole('button',{name:'Rule suite',exact:true}).click();
  await hunt.getByRole('button',{name:'Run selected rules',exact:true}).waitFor();
  await hunt.getByRole('tab',{name:'Indicators',exact:true}).click();
  assert.match(await text.inputValue(),/^event my-existing-draft/,'Bulk draft survives mode round trips');
  await text.fill('ip 192.0.2.1');
  await hunt.getByRole('button',{name:'Run hunt',exact:true}).click();
  await hunt.getByRole('alert').filter({hasText:'Investigation hunts require the desktop query engine.'}).waitFor();
  assert.equal(await page.evaluate(()=>window.huntDiscoveryRuns.hunt),1);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,browserPreview:true,automaticRuns:0,explicitRuns:2,screenshots:fileURLToPath(output),pageErrors:errors.length}));
} finally {await browser.close();await server.close()}
